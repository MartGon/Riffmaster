// Foot pedal: Bluetooth page-turner keys drive playback, practice and sections.
// Needs the dev server on port 5173 and the sample tab. `node pedal.mjs`
import { chromium } from 'playwright-core'

const results = []
const check = (name, ok, extra = '') => {
  results.push(ok)
  console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}${extra ? `  (${extra})` : ''}`)
}
const browser = await chromium.launch({
  executablePath: '/usr/bin/brave-browser', headless: true,
  args: ['--autoplay-policy=no-user-gesture-required', '--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream'],
})
const page = await (await browser.newContext({ viewport: { width: 1280, height: 800 }, permissions: ['microphone'] })).newPage()
const errors = []
page.on('pageerror', (e) => errors.push(String(e)))
await page.goto('http://localhost:5173/')
await page.waitForSelector('.library')
await page.keyboard.press('PageDown')
check('in the library the pedal does nothing', (await page.$('.library')) !== null && errors.length === 0)
await page.setInputFiles('input[type=file]', new URL('../samples/californication.gp', import.meta.url).pathname)
await page.waitForFunction(() => { const play = document.querySelector('.play'); return play && !play.disabled }, null, { timeout: 60000 })
await page.waitForTimeout(800)
const playing = () => page.$eval('.play', (e) => e.getAttribute('aria-label') === 'Pause')
const until = (on) => page.waitForFunction((on) => (document.querySelector('.play')?.getAttribute('aria-label') === 'Pause') === on, on, { timeout: 5000 }).then(() => true, () => false)
const tick = () => page.evaluate(() => window.__riffmaster.api().tickPosition)
const bar = () => page.evaluate(() => {
  const api = window.__riffmaster.api()
  return api.tickCache.masterBars.find((b) => api.tickPosition >= b.start && api.tickPosition < b.end)?.masterBar.index
})

await page.keyboard.press('PageDown')
check('Page Down plays', await until(true))
await page.waitForTimeout(1200)
const scrolled = await page.$eval('.viewport', (e) => e.scrollTop)
await page.keyboard.press('PageUp')
await page.waitForTimeout(250)
check('Page Up goes back to the start and keeps playing', (await tick()) < 1500 && (await playing()), String(await tick()))
check('the page itself does not jump', Math.abs((await page.$eval('.viewport', (e) => e.scrollTop)) - scrolled) < 200)
await page.keyboard.press('PageDown')
check('Page Down stops', await until(false))

// A held pedal repeats its key.
await page.keyboard.down('PageDown')
await page.keyboard.down('PageDown')
await page.keyboard.down('PageDown')
await page.keyboard.up('PageDown')
check('a held pedal counts once', await until(true))
await page.waitForTimeout(700)
check('and stays playing', await playing())
await page.keyboard.press('PageDown')
await until(false)

// Assigning a key.
await page.click('button[title="Foot pedal"]')
await page.waitForSelector('.pedal-rows')
await page.keyboard.press('PageDown')
await page.waitForTimeout(300)
check('with the dialog open the pedal does not play', !(await playing()))
await page.click('button[aria-label="Change the key for Next section"]')
await page.keyboard.press('Space')
check('a key the app needs is refused', /needed by the app/.test(await page.textContent('dialog')))
await page.keyboard.press('KeyN')
await page.waitForTimeout(100)
check('a new key is taken', (await page.textContent('.pedal-row:nth-child(3)')).includes('N'))
await page.click('dialog button:has-text("Done")')
const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('riffmaster.pedal')))
check('it is remembered', stored.next === 'KeyN', JSON.stringify(stored))

const startBar = await bar()
await page.keyboard.press('KeyN')
await page.waitForTimeout(300)
const nextBar = await bar()
check('the next section is reached', nextBar > (startBar ?? 0), `${startBar} -> ${nextBar}`)
await page.keyboard.press('KeyN')
await page.waitForTimeout(300)
check('and the one after', (await bar()) > nextBar, String(await bar()))

// In a slider the arrow keys still belong to the slider, and typing is untouched.
await page.click('button[title="Foot pedal"]')
await page.click('button[aria-label="Change the key for Play / stop"]')
await page.keyboard.press('ArrowRight')
await page.click('dialog button:has-text("Done")')
await page.focus('input[aria-label="Tempo"]')
const before = await page.$eval('input[aria-label="Tempo"]', (e) => e.value)
await page.keyboard.press('ArrowRight')
await page.waitForTimeout(250)
check('an arrow key on a slider moves the slider', !(await playing()) && (await page.$eval('input[aria-label="Tempo"]', (e) => e.value)) !== before)
await page.evaluate(() => document.activeElement?.blur())
await page.click('button[title="Foot pedal"]')
await page.click('dialog button:has-text("Reset")')
await page.click('dialog button:has-text("Done")')
// Page Down on a focused slider is the pedal's, and leaves the slider alone.
await page.focus('input[aria-label="Tempo"]')
const tempo = await page.$eval('input[aria-label="Tempo"]', (e) => e.value)
await page.keyboard.press('PageDown')
check('the pedal does not change a focused slider', (await until(true)) && (await page.$eval('input[aria-label="Tempo"]', (e) => e.value)) === tempo)
await page.keyboard.press('PageDown')
await until(false)
await page.evaluate(() => document.activeElement?.blur())
// Back to the start during a count-in starts the song after a new count-in.
await page.click('button[title="Count-in"]')
await page.evaluate(() => document.activeElement?.blur())
await page.keyboard.press('PageUp')
await page.waitForTimeout(200)
await page.keyboard.press('PageDown')
await until(true)
await page.waitForTimeout(600)
await page.keyboard.press('PageUp')
await page.waitForFunction(() => window.__riffmaster.api().tickPosition > 400, null, { timeout: 9000 }).catch(() => {})
check('Back to the start during a count-in still starts the song', (await tick()) > 400 && (await playing()), String(await tick()))
await page.keyboard.press('PageDown')
await until(false)
await page.click('button[title="Count-in"]')
await page.evaluate(() => document.activeElement?.blur())
// A held pedal does not scroll the tab.
await page.$eval('.viewport', (e) => { e.scrollTop = 300 })
const held = await page.$eval('.viewport', (e) => e.scrollTop)
await page.keyboard.down('PageUp')
await page.keyboard.down('PageUp')
await page.keyboard.up('PageUp')
await page.waitForTimeout(200)
check('a held pedal does not scroll the page', Math.abs((await page.$eval('.viewport', (e) => e.scrollTop)) - held) < 400)
await page.click('button[title="Foot pedal"]')
await page.click('button[aria-label="Change the key for Next section"]')
await page.keyboard.press('Shift+KeyP')
check('a key combination is refused', /single key/.test(await page.textContent('dialog')))
await page.keyboard.press('Escape')
await page.click('dialog button:has-text("Reset")')
await page.click('dialog button:has-text("Done")')

// A practice take.
await page.click('button[title="Practice"]')
await page.waitForFunction(() => !document.querySelector('.practice .button.primary')?.disabled, null, { timeout: 10000 })
await page.evaluate(() => document.activeElement?.blur())
await page.keyboard.press('PageDown')
await page.waitForFunction(() => /Stop/.test(document.querySelector('.practice .button.primary')?.textContent ?? ''), null, { timeout: 5000 })
check('with Practice open the pedal starts a take', true)
await page.waitForTimeout(1200)
const inTake = await tick()
await page.keyboard.press('PageUp')
await page.waitForTimeout(200)
check('during a take Back to the start does nothing', (await tick()) >= inTake)
await page.keyboard.press('PageDown')
await page.waitForFunction(() => /Start practice/.test(document.querySelector('.practice .button.primary')?.textContent ?? ''), null, { timeout: 5000 })
check('the pedal stops the take', true)

// Wait mode.
await page.click('.practice button:has-text("Wait mode")')
await page.waitForSelector('.wait-status')
const atFirst = await tick()
await page.evaluate(() => document.activeElement?.blur())
await page.keyboard.press('PageDown')
await page.waitForTimeout(300)
check('in wait mode the pedal skips the note', (await tick()) > atFirst && (await page.$('.wait-status')) !== null, `${atFirst} -> ${await tick()}`)
await page.click('.practice .button.primary')
await page.waitForTimeout(300)
check('no page errors', errors.length === 0, errors.slice(0, 2).join(' | '))
await browser.close()
const failed = results.filter((ok) => !ok).length
console.log(`\n${results.length - failed} passed, ${failed} failed`)
process.exit(failed ? 1 : 0)
